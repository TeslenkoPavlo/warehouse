'use strict';

let a = '2';

/*
* змінна за замовчуванням a це
* string унарний + конвертує його
* в число 2 далі
* виконується перший кейс тому що
* відбувається строге порівняння
* 2 = 1 + 1
*
* другий кейс не спрацює тому що
* в унарний + вже конвертував
* значення а в число звідси відбувається
* строге порівняння число !== рядку
*
* так можна використовувати вирази
* */
switch(+a) {

    case 1 + 1:
        console.log('Number 2');
        break;

    case '2':
        console.log('String 2');
        break;

    default:
        console.log('Unknown value');
}
