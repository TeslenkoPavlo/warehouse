'use strict';

let height = null;
let width = null;

/*
* оператор нульового злиття має низький пріоритет
* порівняно з іншими операціями
* тому спочатку обрахується множення
* тобто 100 на 0 оскільки null конвертується
* в число нуль потім зліва направо оператор
* нульового злиття перебере значення
* а саме height = null тому пропустить його
* і поверне наступне визначене значення, а саме 0
* */
let area1 = height ?? 100 * width ?? 50;
console.log(area1); // 0

/*
* найвижчий пріоритет тут операцій це дужки
* тому спочатку обраховуються дії всередині них
* перше значення: 100 це визначене значення тому
* оператор нульового злиття поверне його
* далі другі дужки оператор нульового злиття
* поверне число 50 оскільки це число визначене
* далі оператор множення перемножить ці два значення
* і вийде 5000
* */
let area2 = (height ?? 100) * (width ?? 50);
console.log(area2); // 5000
