'use strict';

/*
* якщо користувач спробує скасувати цикл
* то скасується поточний тобто внутрішній
* і після цього виконання повертається до зовнішнього
* циклу збільшуючи і на 1 
* */

/*
* мітка прирває зовнішній цикл та внутрішній одночасно
* */
loop: for(let i = 0; i < 3; i++) {
    for(let j = 0; j < 3; j++) {
        let input =
            prompt(`Координати: ${i}, ${j}`, '');
        if (!input) break loop;
    }
}
