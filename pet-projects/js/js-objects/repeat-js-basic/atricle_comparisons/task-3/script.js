'use strict';

console.log(null > 0); //false
/*
* математичний оператор перетворює null в 0, але нуль не більше нуля тому неправда
* */

console.log(null == 0); // false
/*
* при нестрогому порівнянні null дорівнює тільки undefined в інших випадках false
* */

console.log(null >= 0); // true
/*
* математичний оператор конвертується null в 0, а 0 більше дорівнює нулю, тому правда
* */
